async def init_college_roster():
    print(f"Connecting to {DB_PATH}...")
    await init_db()
    db = await get_db()
    try:
        

        # Also add branch/section columns to students table if not exists
        for col in [
            "ALTER TABLE students ADD COLUMN branch_code TEXT DEFAULT ''",
            "ALTER TABLE students ADD COLUMN section TEXT DEFAULT ''",
            "ALTER TABLE students ADD COLUMN year INTEGER DEFAULT 1",
            "ALTER TABLE students ADD COLUMN class_roll_no TEXT DEFAULT ''",
        ]:
            try:
                await db.execute(col)
            except Exception:
                pass

        count_cur = await db.execute("SELECT COUNT(*) FROM college_roster")
        existing_count = list((await count_cur.fetchone()).values())[0]
        print(f"Existing roster count: {existing_count}")

        # Insert or replace entries
        global inserted
        inserted = 0
        for year, branch_code, section, year_num, semester, class_roll, primary_roll, name in RAW_ROSTER:
            b_name = BRANCH_NAMES.get(branch_code, "Engineering")
            clean_name = name.strip().upper()
            clean_roll = primary_roll.strip().upper()

            await db.execute(
                """
                INSERT INTO college_roster 
                (year, branch_code, branch_name, section, semester, class_roll_no, primary_roll_no, name)
                VALUES (?, ?, ?, ?, ?, ?, ?, ?)
                ON CONFLICT(primary_roll_no) DO NOTHING
                """,
                (year, branch_code, b_name, section, semester, str(class_roll), clean_roll, clean_name),
            )
            inserted += 1

        await db.commit()
    finally:
        await db.close()
        print(f"Successfully seeded {inserted} students across 7 branches & 4 years into college_roster!")

if __name__ == "__main__":
    asyncio.run(init_college_roster())
